import { useTranslation } from 'react-i18next';

import { Button } from '@/components/ui/button';
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog';

import type { AudioAttribution } from '../lib/ackStore';

export interface AttributionDialogProps {
  attribution: AudioAttribution | null;
  onClose: () => void;
}

/** States provenance, never a licence for synthesized audio. Playback is not gated or paused. */
export function AttributionDialog({ attribution, onClose }: AttributionDialogProps) {
  const { t } = useTranslation();
  if (!attribution?.notice.trim()) return null;
  const provider = attribution.audioProvider === 'aquifer' ? 'Aquifer' : 'API.Bible';
  return (
    <Dialog open onOpenChange={open => { if (!open) onClose(); }}>
      <DialogContent showCloseButton={false}>
        <DialogHeader>
          <DialogTitle>{t('ttsAttributionTitle', 'Audio sources & licences')}</DialogTitle>
          <DialogDescription>
            {t('ttsAttributionDescription', 'Source information for this reading. Audio continues while this notice is open.')}
          </DialogDescription>
        </DialogHeader>
        <div className='max-h-[50vh] space-y-3 overflow-y-auto text-sm'>
          <p>
            <span className='font-semibold'>{t('ttsAttributionText', 'Text:')}</span>{' '}
            {attribution.textSourceName}
          </p>
          <p className='whitespace-pre-wrap break-words'>{attribution.notice}</p>
          <p>
            <span className='font-semibold'>{t('ttsAttributionAudio', 'Audio:')}</span>{' '}
            {attribution.audioProvider === 'tts'
              ? t('ttsAttributionGenerated', 'Speech generated by text-to-speech')
              : `${provider}: ${attribution.audioSourceName}`}
          </p>
        </div>
        <DialogFooter>
          <Button onClick={onClose}>{t('ttsAttributionAcknowledge', 'Got it')}</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  );
}
